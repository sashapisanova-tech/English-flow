function n(
  dutch: string,
  english: string,
  article: 'de' | 'het',
  plural: string,
  example: string,
  exampleTranslation: string,
  nounTip?: string,
): FlashcardSetWord {
  return {
    dutch, english, article,
    plural: plural === '-' ? undefined : plural,
    example, exampleTranslation, nounTip,
  };
}

