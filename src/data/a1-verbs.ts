import type { FlashcardSet, FlashcardSetWord, VerbConjugation } from '@/types/dutch';

function t(stem: string): string {
  return stem.endsWith('t') ? stem : stem + 't';
}

function reg(dutch: string, english: string, stem: string, note: string, example: string, exTr: string): FlashcardSetWord {
  return {
    dutch, english, verbType: 'reg', verbNote: note, example, exampleTranslation: exTr,
    conjugation: { ik: stem, jij: t(stem), hij: t(stem), wij: dutch, jullie: dutch, zij: dutch },
  };
}

function irr(dutch: string, english: string, note: string, c: VerbConjugation, example: string, exTr: string): FlashcardSetWord {
  return { dutch, english, verbType: 'irr', verbNote: note, example, exampleTranslation: exTr, conjugation: c };
}

function sep(dutch: string, english: string, note: string, c: VerbConjugation, example: string, exTr: string): FlashcardSetWord {
  return { dutch, english, verbType: 'sep', verbNote: note, example, exampleTranslation: exTr, conjugation: c };
}

function mod(dutch: string, english: string, note: string, c: VerbConjugation, example: string, exTr: string): FlashcardSetWord {
  return { dutch, english, verbType: 'mod', verbNote: note, example, exampleTranslation: exTr, conjugation: c };
}

function vset(id: string, emoji: string, title: string, words: FlashcardSetWord[]): FlashcardSet {
  return { id, emoji, title, category: 'verbs', level: 'A1', folder: 'Verbs', words };
}

