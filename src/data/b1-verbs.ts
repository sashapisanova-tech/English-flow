import type { FlashcardSet, FlashcardSetWord, VerbConjugation } from '@/types/dutch';

function t(stem: string): string {
  return stem.endsWith('t') ? stem : stem + 't';
}

function autoPast(dutch: string, stem: string): { pastTense: string; pastParticiple: string } {
  const s = /[aeiou]$/.test(stem) ? stem.slice(0, -1) : stem;
  const base = dutch.replace(/en$/, '');
  const isVoicedDevoiced = (s.endsWith('f') && base.endsWith('v')) || (s.endsWith('s') && base.endsWith('z'));
  const isSK = !isVoicedDevoiced && (s.endsWith('ch') || ['t','k','f','s','p'].includes(s.slice(-1)));
  const sg = s + (isSK ? 'te' : 'de');
  const pl = sg + 'n';
  const NO_GE = ['be', 'ge', 'ver', 'ont', 'er', 'her'];
  const gePrefix = NO_GE.some(p => dutch.toLowerCase().startsWith(p)) ? '' : 'ge';
  const pEnd = isSK ? 't' : 'd';
  const pStem = s.slice(-1) === pEnd ? s : s + pEnd;
  return { pastTense: `${sg} / ${pl}`, pastParticiple: gePrefix + pStem };
}

function reg(dutch: string, english: string, stem: string, note: string, example: string, exTr: string, pastOverride?: string, ppOverride?: string): FlashcardSetWord {
  const { pastTense, pastParticiple } = autoPast(dutch, stem);
  return { dutch, english, verbType: 'reg', verbNote: note, example, exampleTranslation: exTr,
    conjugation: { ik: stem, jij: t(stem), hij: t(stem), wij: dutch, jullie: dutch, zij: dutch },
    pastTense: pastOverride ?? pastTense, pastParticiple: ppOverride ?? pastParticiple };
}

function irr(dutch: string, english: string, note: string, c: VerbConjugation, example: string, exTr: string, past?: string, pp?: string): FlashcardSetWord {
  return { dutch, english, verbType: 'irr', verbNote: note, example, exampleTranslation: exTr, conjugation: c, pastTense: past, pastParticiple: pp };
}

function sep(dutch: string, english: string, note: string, c: VerbConjugation, example: string, exTr: string, past?: string, pp?: string): FlashcardSetWord {
  return { dutch, english, verbType: 'sep', verbNote: note, example, exampleTranslation: exTr, conjugation: c, pastTense: past, pastParticiple: pp };
}

function vset(id: string, emoji: string, title: string, words: FlashcardSetWord[]): FlashcardSet {
  return { id, emoji, title, category: 'verbs', level: 'B1', folder: 'Verbs', words };
}

